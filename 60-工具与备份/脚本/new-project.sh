#!/usr/bin/env bash
# 项目诞生的单一入口（R1）
# 一个命令建好：主目录 + 全员工位 + 通用开场白 + 人员分配表 + 项目说明 + 检查清单
set -u
COMPANY="/storage/emulated/0/AI专用文件夹/AI公司"
P="${1:?用法: new-project.sh <项目名>}"
STAGE="${2:-进行中}"

# --- Q-03：命名合法性统一校验（R2 也复用） ---
if [[ "$P" =~ [[:space:]/\\:*?\"\<\>|] ]]; then
  echo "✗ 项目名含空格或非法字符（/ \\ : * ? \" < > |）：$P"; exit 2
fi
case "$STAGE" in 进行中|已完成|已搁置) ;; *) echo "✗ 状态只能是 进行中/已完成/已搁置"; exit 2;; esac

PROJ="$COMPANY/20-项目区/$STAGE/$P"
if [ -e "$PROJ" ]; then echo "✗ 项目已存在：$PROJ"; exit 1; fi

echo "════════════════════════════════════"
echo "  新建项目（单一入口）"
echo "════════════════════════════════════"
echo "  项目名：$P"
echo "  状态：$STAGE"
echo
echo "  ⚠ Q-02：请确认项目名无误（董事长已认可）。Ctrl+C 可取消。"
echo

# 1. 主目录骨架
mkdir -p "$PROJ/01-材料本体" "$PROJ/02-各方意见" "$PROJ/05-产出"
echo "  ✓ 主目录骨架"

# 1b. 项目问题需求池（跟项目走，归档/交接自动带上）
if [ ! -f "$PROJ/00-问题需求池.md" ]; then
cat > "$PROJ/00-问题需求池.md" <<'POOLEOF'
# 项目问题需求池 · 项目名待填

> 跟项目走：归档/交接/打包自动带上。公司级的事去根目录 `11-问题需求池.md`。

## 一、待处理
### 需求（P-REQ）
### 问题（P-BUG）
### 优化（P-OPT）
## 二、处理中
## 三、已完成（留痕，不删除）
## 四、已搁置（含理由）
## 五、编号登记表
- 下一个编号：P-REQ-001 / P-BUG-001 / P-OPT-001
POOLEOF
echo "  ✓ 项目问题需求池（00-问题需求池.md）"
fi

# 2. 全员工位子目录（R1：不再手工循环漏掉）
for w in "$COMPANY/10-办公区"/*/; do
  mkdir -p "$w/$P"
  echo "# $(basename "$w") — $P" > "$w/$P/README.md"
done
echo "  ✓ 7 个工位子目录"

# 3. 通用开场白（Q-09：固定，随项目自动带）
cp "$COMPANY/02-制度与模板/00-通用开场白-每次新对话第一句.md" "$PROJ/00-通用开场白.md"
echo "  ✓ 通用开场白"

# 4. 人员分配表模板（Q-10：立项第一张产出）
cat > "$PROJ/00-人员分配表.md" <<EOF
# 人员分配表 — $P

**规则：立项后第一张产出，先定人再派活。**

| 工位 | 谁 | 参与? | 本项目的活 | 能被 DSH 读到? |
|---|---|---|---|---|
| 01-总经理室 | DSH | ✅ 主持 | 汇总/验收/记录 | — |
| 00-秘书台 | YG | ✅ 传话 | 转发任务与材料 | — |
| 02-分析部 | ChatGPT | ⬜ 待定 |  | ✅ 能 |
| 03-文档部 | 千问 | ⬜ 待定 |  | ✅ 能 |
| 04-技术部 | 大肥鱼 | ⬜ 待定 |  | ✅ 能 |
| 05-视觉部 | 豆包 | ⏭ 跳过 | 对话私有加密读不到 | ❌ 读不到 |
| 06-情报部 | Grok | ⏭ 跳过 | 对话位置未确认 | ❌ 未确认 |

> 可参与名单与跳过理由必须填（Q-08）。
EOF
echo "  ✓ 人员分配表模板"

# 5. 项目说明模板
cat > "$PROJ/00-项目说明.md" <<EOF
# $P

**立项日期：** $(date +%Y-%m-%d)
**负责人：** DSH
**状态：** $STAGE

## 目标
（一句话）

## 范围
**做：** 
**不做：** 

## 材料本体（Q-11：被处理/被评审的原始资料放 01-材料本体/）
- [ ] 已放入

## 验收标准
| ID | 标准 | 状态 |
|---|---|---|
| T-01 |  | ⬜ |
EOF
echo "  ✓ 项目说明模板"

# 6. 派活/启动检查清单（把 R3 能力边界固化进流程）
cp "$COMPANY/02-制度与模板/01-项目启动检查清单.md" "$PROJ/00-启动检查清单.md" 2>/dev/null || true

echo
echo "════════════════════════════════════"
echo "  ✅ 项目骨架已建：$PROJ"
echo "  下一步：填 00-项目说明 / 00-人员分配表 / 01-材料本体"
echo "════════════════════════════════════"
